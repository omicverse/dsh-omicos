import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { mkdtemp, rm } from 'node:fs/promises'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { ScienceLedger } from '../src/oss/ledger.js'
import type { MemoryDraft, MemoryNode } from '../src/oss/memory-types.js'
let directory: string; let ledger: ScienceLedger
const owner = { owner: true, actor: 'user:fixture' }
const a = { sessionId: 'session-a', actor: 'harness:a' }; const b = { sessionId: 'session-b', actor: 'harness:b' }
let sequence = 0
const op = () => `memory-${++sequence}`
beforeEach(async () => { directory = await mkdtemp(join(tmpdir(), 'oss-memory-')); ledger = await ScienceLedger.open(directory) })
afterEach(async () => { ledger.close(); await rm(directory, { recursive: true, force: true }) })
const draft = (change: Partial<MemoryDraft> = {}): MemoryDraft => ({ title: 'Reference', text: 'GRCh38', kind: 'fact', scope: 'project', sources: [{ kind: 'user', ref: 'Explicit researcher statement' }], operationId: op(), ...change })
const confirm = (node: MemoryNode, extra = {}, access = owner) => ledger.memory.transition({ id: node.id, revision: node.revision, action: 'confirm', operationId: op(), ...extra }, access)
describe('revisioned, scoped scientific memory', () => {
  it('keeps proposals out of context and retains immutable revisions through confirmation, edits and withdrawal', () => {
    const proposed = ledger.memory.propose(draft(), a)
    expect(ledger.memories('session-a')).toEqual([])
    const confirmed = confirm(proposed)
    expect(ledger.memories('session-b')[0].text).toBe('GRCh38')
    const request = draft({ id: confirmed.id, revision: confirmed.revision, text: 'GRCh37' })
    const revised = ledger.memory.propose(request, a)
    expect(ledger.memories()).toEqual([])
    const final = confirm(revised)
    expect(ledger.memory.propose(request, a).revision).toBe(final.revision)
    expect(() => ledger.memory.propose({ ...request, text: 'different request' }, a)).toThrow(/another request/)
    expect(() => ledger.memory.transition({ id: final.id, revision: 1, action: 'withdraw', operationId: op() }, owner)).toThrow(/current revision/)
    ledger.memory.transition({ id: final.id, revision: final.revision, action: 'withdraw', operationId: op(), reason: 'Old reference superseded' }, owner)
    expect(ledger.memories()).toEqual([])
    expect(ledger.memory.history(final.id, owner).revisions.map(node => node.state)).toEqual(['withdrawn', 'confirmed', 'proposed', 'confirmed', 'proposed'])
    expect(ledger.memory.get(final.id, owner, 1).text).toBe('GRCh38')
  })
  it('separates private session notes and proposals, with explicit promotion of sourced session content', () => {
    const note = confirm(ledger.memory.propose(draft({ scope: 'session', sessionId: a.sessionId, text: 'Private session observation' }), a))
    expect(() => ledger.memory.get(note.id, b)).toThrow(/not available/)
    expect(ledger.memory.context(b).entries).toEqual([])
    const shared = ledger.memory.propose(draft({ kind: 'summary', text: 'Approved cross-session summary', sources: [{ kind: 'memory', ref: note.id, revision: note.revision }] }), a)
    expect(ledger.memory.list(b).entries).toEqual([])
    expect(() => confirm(shared, {}, a)).toThrow(/Explicitly approve sharing/)
    const promoted = confirm(shared, { allowScopePromotion: true }, a)
    expect(ledger.memory.context(b).entries[0].text).toBe(promoted.text)
    expect(() => ledger.memory.get(note.id, b)).toThrow(/not available/)
    expect(() => ledger.memory.legacy(note.id, 'overwrite', 'unrelated session', b)).toThrow(/not available/)
    expect(ledger.memory.get(note.id, a).text).toBe('Private session observation')
  })
  it('consolidates approved sources atomically, and invalidates summaries when their source revision is withdrawn', () => {
    const first = confirm(ledger.memory.propose(draft({ title: 'Organism', text: 'Human samples' }), owner))
    const second = confirm(ledger.memory.propose(draft({ title: 'Reference', text: 'GRCh38' }), owner))
    const summary = ledger.memory.propose(draft({ kind: 'summary', title: 'Study context', text: 'Human samples aligned to GRCh38', sources: [first, second].map(node => ({ kind: 'memory' as const, ref: node.id, revision: node.revision })) }), owner)
    const accepted = confirm(summary, { supersedeSources: true })
    expect(ledger.memories().map(node => node.id)).toEqual([accepted.id])
    expect(ledger.memory.get(first.id, owner).state).toBe('superseded')
    expect(ledger.memory.view(accepted.id, owner).effective).toBe(true)
    const source = ledger.memory.get(first.id, owner)
    ledger.memory.transition({ id: source.id, revision: source.revision, action: 'withdraw', operationId: op() }, owner)
    expect(ledger.memories()).toEqual([])
    expect(ledger.memory.view(accepted.id, owner).issues.join(' ')).toContain('Source revision changed')
    expect(ledger.memory.history(first.id, owner).revisions.at(-1)?.text).toBe('Human samples')
  })
  it('requires direct session promotion approval and rolls back consolidation of dependent source sets', () => {
    const note = confirm(ledger.memory.propose(draft({ scope: 'session', sessionId: a.sessionId }), a))
    const promoted = ledger.memory.propose(draft({ id: note.id, revision: note.revision, scope: 'project' }), a)
    expect(() => confirm(promoted)).toThrow(/Explicitly approve sharing/)
    const shared = confirm(promoted, { allowScopePromotion: true })
    const dependent = confirm(ledger.memory.propose(draft({ kind: 'summary', sources: [{ kind: 'memory', ref: shared.id }] }), owner))
    const merge = ledger.memory.propose(draft({ kind: 'summary', sources: [shared, dependent].map(node => ({ kind: 'memory' as const, ref: node.id })) }), owner)
    expect(() => confirm(merge, { supersedeSources: true })).toThrow(/dependent source/)
    expect(ledger.memory.get(shared.id, owner).revision).toBe(shared.revision)
    expect(ledger.memory.get(dependent.id, owner).state).toBe('confirmed')
    expect(ledger.memory.get(merge.id, owner).state).toBe('proposed')
  })
  it('enforces topic visibility and acyclic hierarchy, without deleting confirmed descendants', () => {
    const root = confirm(ledger.memory.propose(draft({ kind: 'topic', title: 'Study', text: '', sources: [] }), owner))
    const child = confirm(ledger.memory.propose(draft({ kind: 'topic', title: 'Reference settings', text: '', sources: [], parentId: root.id }), owner))
    const fact = confirm(ledger.memory.propose(draft({ parentId: child.id }), owner))
    expect(() => ledger.memory.transition({ id: root.id, revision: root.revision, action: 'move', parentId: child.id, operationId: op() }, owner)).toThrow(/acyclic/)
    expect(() => ledger.memory.propose(draft({ id: root.id, revision: root.revision, kind: 'topic', scope: 'session', sessionId: a.sessionId }), owner)).toThrow(/narrow visibility/)
    ledger.memory.transition({ id: root.id, revision: root.revision, action: 'withdraw', operationId: op() }, owner)
    expect(ledger.memory.get(fact.id, owner).state).toBe('confirmed')
    expect(ledger.memory.view(fact.id, owner).effective).toBe(false)
    expect(ledger.memories()).toEqual([])
  })
  it('checks local receipt evidence, labels declared sources, and paginates without leaking private entries', async () => {
    ledger.saveExecutions('python', [{ id: 'receipt', operationId: 'receipt', sessionId: a.sessionId, language: 'python', state: 'succeeded', code: 'print(42)', output: '42', artifacts: [], createdAt: new Date().toISOString() }])
    const sourced = ledger.memory.propose(draft({ sources: [{ kind: 'execution', ref: 'receipt' }, { kind: 'file', ref: 'data.h5ad' }] }), owner)
    expect(sourced.sources[0].verification).toBe('local-receipt'); expect(sourced.sources[1].verification).toBe('declared')
    expect(() => ledger.memory.propose(draft({ sources: [{ kind: 'execution', ref: 'missing' }] }), owner)).toThrow(/completed local/)
    for (let count = 0; count < 4; count++) confirm(ledger.memory.propose(draft({ title: `fact-${count}` }), owner))
    confirm(ledger.memory.propose(draft({ scope: 'session', sessionId: a.sessionId, text: 'session-only' }), a))
    const first = ledger.memory.list(b, { limit: 2 }); const next = ledger.memory.list(b, { limit: 2, before: first.next })
    expect(first.entries).toHaveLength(2); expect(next.entries).toHaveLength(2)
    expect(new Set([...first.entries, ...next.entries].map(entry => entry.node.id)).size).toBe(4)
    expect(JSON.stringify(first)).not.toContain('session-only')
    expect(ledger.memory.context(b, 1).entries).toEqual([])
    ledger.close(); ledger = await ScienceLedger.open(directory)
    expect(ledger.memory.get(sourced.id, owner).sources[0].verification).toBe('local-receipt')
  })
})
